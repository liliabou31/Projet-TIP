clearvars; close all

% 1. Paramètres d'entraînement
inputSize = [224 224 3];
miniBatch = 64;
maxEpochs = 10;
learnRate = 1e-4;

% 2. Chargement des données et des classes
load("food11_pretraitees_data.mat", "augImdsTrain", "augImdsVal", "imdsTrain", "imdsVal");
classNames = categories(imdsTrain.Labels);
numClasses = numel(classNames);

% 3. Augmentation de données et redimensionnement
augmenter = imageDataAugmenter( ...
    RandXReflection=true, ...
    RandRotation=[-15 15], ...
    RandScale=[0.9 1.1], ...
    FillValue=128);
augimdsTrain = augmentedImageDatastore(inputSize(1:2), imdsTrain, ...
    DataAugmentation=augmenter);
augimdsVal = augmentedImageDatastore(inputSize(1:2), imdsVal);

% 4. Chargement du modèle pré-entraîné MobileNetV2
net = imagePretrainedNetwork("mobilenetv2", NumClasses=numClasses);

% 5. Gel des couches existantes (on n'entraîne que la dernière couche de classification)
headName = net.Learnables.Layer(end);
for i = 1:height(net.Learnables)
    if net.Learnables.Layer(i) ~= headName
        net = setLearnRateFactor(net, net.Learnables.Layer(i), net.Learnables.Parameter(i), 0);
    end
end

% 6. Configuration des options et lancement de l'entraînement
options = trainingOptions("adam", ...
    InitialLearnRate=learnRate, ...
    LearnRateSchedule="piecewise", ...
    LearnRateDropPeriod=3, ...
    LearnRateDropFactor=0.5, ...
    MaxEpochs=maxEpochs, ...
    MiniBatchSize=miniBatch, ...
    L2Regularization=1e-4, ...
    Shuffle="every-epoch", ...
    ValidationData=augimdsVal, ...
    ValidationFrequency=100, ...
    ValidationPatience=5, ...
    Metrics="accuracy", ...
    Plots="training-progress", ...
    Verbose=false);

net = trainnet(augimdsTrain, net, "crossentropy", options);

% 7. Sauvegarde du modèle entraîné
save("transfert_mobilenetv2.mat", "net", "imdsVal");
